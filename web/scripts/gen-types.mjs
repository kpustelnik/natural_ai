// Generate src/generated/schemas.ts from ../schemas/web/*.schema.json.
// The JSON Schemas come from the pydantic models (uv run python -m metro_agh.schemas.export).
// All files are merged into one schema so shared types (Provenance, BufferView, ...) are
// emitted once.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "schemas", "web");
const outFile = join(here, "..", "src", "generated", "schemas.ts");

// Pydantic emits JSON Schema 2020-12; json-schema-to-typescript expects older drafts.
// - drop per-field "title" (otherwise every field becomes its own type alias)
// - tuples: "prefixItems" -> "items" array
function normalise(node, isModel = false) {
  if (Array.isArray(node)) return node.map((n) => normalise(n));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !isModel) continue;
    if (key === "prefixItems") {
      out.items = value.map((n) => normalise(n));
      out.minItems = value.length;
      out.maxItems = value.length;
    } else if (key === "properties") {
      out.properties = Object.fromEntries(
        Object.entries(value).map(([name, prop]) => [name, normalise(prop)]),
      );
    } else if (key === "$defs") {
      out.$defs = Object.fromEntries(
        Object.entries(value).map(([name, def]) => [name, normalise(def, true)]),
      );
    } else {
      out[key] = normalise(value);
    }
  }
  return out;
}

const defs = {};
const roots = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = normalise(JSON.parse(readFileSync(join(schemaDir, file), "utf8")), true);
  const { $defs = {}, ...root } = schema;
  Object.assign(defs, $defs);
  defs[root.title] = root;
  roots[file.replace(".schema.json", "")] = { $ref: `#/$defs/${root.title}` };
}

const bundle = {
  title: "WebData",
  type: "object",
  properties: roots,
  required: Object.keys(roots),
  additionalProperties: false,
  $defs: defs,
};

const ts = await compile(bundle, "WebData", {
  bannerComment:
    "/* Generated by scripts/gen-types.mjs from schemas/web. Do not edit; run `npm run gen:types`. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
});

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts.replaceAll("\r\n", "\n"));
console.log(`wrote ${outFile}`);
